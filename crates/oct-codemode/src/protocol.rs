use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::BTreeMap;

pub const MAX_FRAME: usize = 32 * 1024 * 1024;
pub const PROTOCOL_VERSION: u32 = 3;
pub const MAX_CODE: usize = 256 * 1024;
pub const MAX_ARGS: usize = 1024 * 1024;
pub const MAX_SELECTOR: usize = 4 * 1024;
pub const MAX_RESULT: usize = 8 * 1024 * 1024;
pub const MAX_OUTPUT: usize = 16 * 1024 * 1024;
pub const MAX_CALLS: u64 = 128;
pub const CONCURRENCY: usize = 8;
pub const MAX_PENDING_CALL_BYTES: usize = CONCURRENCY * MAX_ARGS;

/// Safe, catchable host failure. Codes are stable; optional data stays in JS.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CallError {
    pub code: String,
    pub message: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub result: Option<Value>,
}

impl CallError {
    pub fn new(code: &str, message: impl Into<String>) -> Self {
        Self {
            code: code.into(),
            message: message.into().chars().take(8192).collect(),
            result: None,
        }
    }
    pub fn from_error(error: anyhow::Error) -> Self {
        let error = match error.downcast::<Self>() {
            Ok(error) => return error,
            Err(error) => error,
        };
        let message = format!("{error:#}");
        if json_size_within(&message, MAX_RESULT).is_none() {
            Self::new(
                "result_too_large",
                "Tool result exceeds code mode budget; request a smaller page",
            )
        } else {
            Self::new("tool_error", message)
        }
    }
}
impl std::fmt::Display for CallError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.message)
    }
}
impl std::error::Error for CallError {}

/// Measure serialized payloads without allocating another copy, stopping at
/// the budget even for strings that expand substantially through JSON escaping.
pub fn json_size_within(value: &impl Serialize, limit: usize) -> Option<usize> {
    struct Counter {
        bytes: usize,
        limit: usize,
    }
    impl std::io::Write for Counter {
        fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
            if buf.len() > self.limit - self.bytes {
                return Err(std::io::Error::other("JSON payload exceeds budget"));
            }
            self.bytes += buf.len();
            Ok(buf.len())
        }
        fn flush(&mut self) -> std::io::Result<()> {
            Ok(())
        }
    }
    let mut counter = Counter { bytes: 0, limit };
    serde_json::to_writer(&mut counter, value).ok()?;
    Some(counter.bytes)
}

/// Both sides validate before retaining a call in their pending queues.
pub fn call_payload_size(tool: &str, args: &Value) -> anyhow::Result<usize> {
    anyhow::ensure!(
        tool.len() <= MAX_SELECTOR,
        "Code mode selector exceeds limit"
    );
    let args_bytes = json_size_within(args, MAX_ARGS)
        .ok_or_else(|| anyhow::anyhow!("Code mode arguments exceed limit"))?;
    Ok(tool.len() + args_bytes)
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Init {
    pub code: String,
    /// Relative SDK paths, generated by the host. Never filesystem paths.
    pub modules: BTreeMap<String, String>,
    pub timeout_ms: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum FromWorker {
    Hello { protocol_version: u32 },
    Call { seq: u64, tool: String, args: Value },
    Emit { text: String },
    Image { mime_type: String, data: String },
    Done { error: Option<String> },
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ToWorker {
    Init(Init),
    Reply {
        seq: u64,
        result: Result<Value, CallError>,
    },
}

pub async fn read_frame<R: tokio::io::AsyncRead + Unpin, T: serde::de::DeserializeOwned>(
    r: &mut R,
) -> anyhow::Result<T> {
    use tokio::io::AsyncReadExt;
    let len = r.read_u32().await? as usize;
    anyhow::ensure!(len <= MAX_FRAME, "Code mode protocol frame exceeds limit");
    let mut data = vec![0; len];
    r.read_exact(&mut data).await?;
    Ok(serde_json::from_slice(&data)?)
}

pub async fn write_frame<W: tokio::io::AsyncWrite + Unpin, T: Serialize>(
    w: &mut W,
    value: &T,
) -> anyhow::Result<()> {
    use tokio::io::AsyncWriteExt;
    let data = serde_json::to_vec(value)?;
    anyhow::ensure!(
        data.len() <= MAX_FRAME,
        "Code mode protocol frame exceeds limit"
    );
    w.write_u32(data.len() as u32).await?;
    w.write_all(&data).await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn json_budget_counts_escaping_and_accepts_the_exact_limit() {
        let value = json!({"data":"\0\n\"é"});
        let bytes = serde_json::to_vec(&value).unwrap().len();
        assert_eq!(json_size_within(&value, bytes), Some(bytes));
        assert_eq!(json_size_within(&value, bytes - 1), None);
        assert_eq!(json_size_within(&value, 0), None);
    }

    #[test]
    fn call_budget_includes_selector_and_validates_it_before_arguments() {
        let args = json!({"n":1});
        let selector = "x".repeat(MAX_SELECTOR);
        assert_eq!(
            call_payload_size(&selector, &args).unwrap(),
            MAX_SELECTOR + 7
        );
        let error = call_payload_size(&(selector + "x"), &json!("x".repeat(MAX_ARGS))).unwrap_err();
        assert!(error.to_string().contains("selector exceeds limit"));
        assert!(call_payload_size("echo", &json!("\0".repeat(MAX_ARGS / 6 + 1))).is_err());
    }
}
